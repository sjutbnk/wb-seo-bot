# ─────────────────────────────────────────────────────────────────────────────
# Построение промпта
# ─────────────────────────────────────────────────────────────────────────────

def _build_prompt(
    user_query: str,
    suggestions: list[str],
    competitors: list[CompetitorProduct],
    mode: GenerateMode,
    keyword_stats: dict[str, int] | None = None,
) -> str:
    # Ключевые слова
    if suggestions:
        kw_parts = []
        for kw in suggestions:
            freq = keyword_stats.get(kw) if keyword_stats else None
            suffix = f" (~{freq:,} показов/мес)".replace(",", " ") if freq else ""
            kw_parts.append(f"  • {kw}{suffix}")
        kw_block = "\n".join(kw_parts)
    else:
        kw_block = "  (не найдены — ориентируйся на запрос продавца)"

    # Конкуренты
    if competitors:
        comp_parts = []
        for i, c in enumerate(competitors[:8], 1):
            desc = c.description.strip()
            preview = (desc[:500] + "…") if len(desc) > 500 else (desc or "описание не загружено")
            comp_parts.append(
                f"[{i}] «{c.name}» | {c.brand} | {c.subject_name}\n"
                f"    {preview}"
            )
        comp_block = "\n\n".join(comp_parts)
    else:
        comp_block = "(конкуренты не загружены)"

    # Что генерировать
    sections_map: dict[GenerateMode, str] = {
        "all": _SECTIONS_ALL,
        "description": _SECTIONS_DESCRIPTION,
        "keywords": _SECTIONS_KEYWORDS,
        "analysis": _SECTIONS_ANALYSIS,
    }
    task_block = sections_map[mode]

    return f"""
═══════════════════════════════════════════
ВХОДНЫЕ ДАННЫЕ
═══════════════════════════════════════════

Товар: «{user_query}»

── Ключевые слова из WB (реальные запросы покупателей) ──
{kw_block}

── Топ конкурентов в выдаче WB ──
{comp_block}

═══════════════════════════════════════════
ЗАДАНИЕ
═══════════════════════════════════════════

Проанализируй конкурентов:
— Что они делают правильно (взять на вооружение)
— Что они упускают (использовать как преимущество)
— Какие ВЧ-ключи в названиях, какие выгоды закрывают

{task_block}
"""


