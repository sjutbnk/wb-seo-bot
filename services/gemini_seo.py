# ─────────────────────────────────────────────────────────────────────────────
# Основная функция генерации
# ─────────────────────────────────────────────────────────────────────────────

async def generate_seo_card(
    user_query: str,
    suggestions: list[str],
    competitors: list[CompetitorProduct],
    mode: GenerateMode = "all",
    keyword_stats: dict[str, int] | None = None,
) -> dict[str, str]:
    prompt = _build_prompt(user_query, suggestions, competitors, mode, keyword_stats)
    model_chain = _build_model_chain()
    last_error: Exception | None = None

    for model_name in model_chain:
        try:
            logger.info("Gemini модель: %s | режим: %s", model_name, mode)
            model = genai.GenerativeModel(
                model_name=model_name,
                system_instruction=_SYSTEM_PROMPT,
            )
            response = await model.generate_content_async(
                prompt,
                generation_config=genai.GenerationConfig(
                    temperature=0.8,
                    max_output_tokens=3000,
                ),
            )
            logger.info("Успешно: %s", model_name)
            return _parse_response(response.text)

        except Exception as e:
            err = str(e).lower()
            if any(c in err for c in ("429", "503", "overload", "unavailable", "404", "not found")):
                logger.warning("Модель %s недоступна: %s", model_name, e)
                last_error = e
                continue
            logger.error("Критическая ошибка Gemini [%s]: %s", model_name, e)
            raise RuntimeError(f"Ошибка Gemini: {e}") from e

    raise RuntimeError(f"Все модели недоступны. Последняя ошибка: {last_error}") from last_error


def _build_model_chain() -> list[str]:
    chain = list(_FALLBACK_MODELS)
    custom = settings.GEMINI_MODEL.strip()
    if custom and custom not in chain:
        chain.insert(0, custom)
    return chain


# ─────────────────────────────────────────────────────────────────────────────
# Парсинг ответа
# ─────────────────────────────────────────────────────────────────────────────

def _parse_response(raw: str) -> dict[str, str]:
    sections: dict[str, str] = {
        "title": "", "description": "", "keywords": "", "analysis": "", "raw": ""
    }
    markers = {
        "### НАЗВАНИЕ": "title",
        "### ОПИСАНИЕ": "description",
        "### КЛЮЧЕВЫЕ СЛОВА": "keywords",
        "### АНАЛИЗ КОНКУРЕНТОВ": "analysis",
        "### АНАЛИЗ": "analysis",
    }

    current: str | None = None
    buf: list[str] = []

    for line in raw.split("\n"):
        stripped = line.strip()
        matched = next(
            (key for marker, key in markers.items() if stripped.startswith(marker)),
            None,
        )
        if matched:
            if current is not None:
                sections[current] = "\n".join(buf).strip()
            current = matched
            buf = []
        elif current is not None and not stripped.startswith("───"):
            buf.append(line)

    if current is not None and buf:
        sections[current] = "\n".join(buf).strip()

    if not any(sections[k] for k in ("title", "description", "keywords", "analysis")):
        sections["raw"] = raw

    return sections
